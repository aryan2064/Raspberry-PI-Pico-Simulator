import { Button, Circuit, LED, PicoBoard } from "../engine";
import type { Pin } from "../engine";
import type {
  AddComponentMessage,
  ConnectMessage,
  DisconnectMessage,
  MainToWorkerMessage,
  PressReleaseMessage,
  RemoveComponentMessage,
  RunMessage,
  SnapshotMessage,
} from "./messages";

// The Circuit instance that Python code manipulates lives here, physically
// on whichever thread runs the host. A browser Worker cannot share JS object
// references with the main thread — only postMessage (structured clone)
// crosses that boundary — so for machine.Pin.value() to behave like a
// synchronous read-after-write from Python's perspective, the live Circuit
// must be in the same thread as Pyodide: the worker thread.
//
// CircuitHost is deliberately free of Worker/Pyodide APIs: it is just the
// Circuit plus a thin command surface. The worker file wires it to the real
// `self.onmessage` / Pyodide; tests drive it directly.
export class CircuitHost {
  readonly circuit = new Circuit();

  // main-thread wireId (from the topology record) -> engine Wire id
  // (generated by Circuit.connect(), not under our control).
  private wireIdToEngineWireId = new Map<string, string>();

  componentById(id: string) {
    return this.circuit.components.find((c) => c.id === id);
  }

  private board(): PicoBoard {
    const board = this.circuit.components.find((c) => c instanceof PicoBoard);
    if (!board) {
      throw new Error("machine.Pin needs a PicoBoard in the circuit");
    }
    return board;
  }

  private pinFor(componentId: string, label: string): Pin {
    const component = this.componentById(componentId);
    if (!component) {
      throw new Error(`No component with id "${componentId}"`);
    }
    return component.pin(label);
  }

  // Applies any edit message (everything except "run", which needs Pyodide and
  // is handled by worker code, not by the host). Throws on invalid input — the
  // worker turns thrown errors into { type: "error" } posts.
  handleEdit(msg: Exclude<MainToWorkerMessage, RunMessage>): void {
    switch (msg.type) {
      case "addComponent":
        this.addComponent(msg);
        break;
      case "connect":
        this.connect(msg);
        break;
      case "disconnect":
        this.disconnect(msg);
        break;
      case "press":
        this.press(msg);
        break;
      case "release":
        this.release(msg);
        break;
      case "removeComponent":
        this.removeComponent(msg);
        break;
    }
  }

  addComponent(msg: AddComponentMessage): void {
    if (this.componentById(msg.componentId)) {
      return; // replay-safe: the same id may be sent again after a rebuild
    }
    switch (msg.kind) {
      case "pico_board":
        this.circuit.addComponent(new PicoBoard(msg.componentId));
        break;
      case "led":
        this.circuit.addComponent(new LED(msg.componentId));
        break;
      case "button":
        this.circuit.addComponent(new Button(msg.componentId));
        break;
    }
  }

  connect(msg: ConnectMessage): void {
    const pinA = this.pinFor(msg.pinOwnerIdA, msg.pinLabelA);
    const pinB = this.pinFor(msg.pinOwnerIdB, msg.pinLabelB);
    const wire = this.circuit.connect(pinA, pinB);
    this.wireIdToEngineWireId.set(msg.wireId, wire.id);
    this.circuit.resolveNets();
  }

  disconnect(msg: DisconnectMessage): void {
    const engineWireId = this.wireIdToEngineWireId.get(msg.wireId);
    if (engineWireId === undefined) {
      return; // unknown id (or already removed) — nothing to do
    }
    this.circuit.disconnect(engineWireId);
    this.wireIdToEngineWireId.delete(msg.wireId);
    this.circuit.resolveNets();
  }

  // Removes a component and (via the engine cascade) every wire touching its
  // pins. The board is exempt: it is the substrate every Python script needs,
  // so removing it is refused — the worker turns the thrown error into an
  // { type: "error" } post and the component stays put.
  removeComponent(msg: RemoveComponentMessage): void {
    const component = this.componentById(msg.componentId);
    if (!component) {
      return; // unknown id — nothing to remove (replay-safe no-op)
    }
    if (component instanceof PicoBoard) {
      throw new Error("Cannot remove the PicoBoard");
    }
    this.circuit.removeComponent(msg.componentId);
    // The cascade removed some engine wires; drop their topology keys so a
    // later disconnect() can never target a ghost wire id.
    this.wireIdToEngineWireId = new Map(
      [...this.wireIdToEngineWireId].filter(([, engineWireId]) =>
        this.circuit.wires.some((w) => w.id === engineWireId)
      )
    );
    this.circuit.resolveNets();
  }

  press(msg: PressReleaseMessage): void {
    this.buttonFor(msg.componentId).press();
  }

  release(msg: PressReleaseMessage): void {
    this.buttonFor(msg.componentId).release();
  }

  private buttonFor(id: string): Button {
    const component = this.componentById(id);
    if (!(component instanceof Button)) {
      throw new Error(`Component "${id}" is not a button`);
    }
    return component;
  }

  // ---- one simulation step + snapshot (driven by the worker's own loop) ----

  tick(dt = 1 / 60): void {
    this.circuit.tick(dt);
  }

  getSnapshot(): SnapshotMessage {
    const conflictedPinIds: string[] = [];
    const components = this.circuit.components.map((c) => {
      for (const p of c.pins) {
        if (p.hasConflict) {
          conflictedPinIds.push(p.id);
        }
      }
      return {
        id: c.id,
        renderInfo: c.getRenderInfo(),
        pins: c.pins.map((p) => ({ id: p.id, label: p.label })),
      };
    });
    return {
      type: "snapshot",
      components,
      conflictedPinIds,
    };
  }

  // ---- machine.Pin bridge (worker -> Pyodide -> here, all one thread) ----

  // mode: 0 = IN, 1 = OUT (mirrors the machine.Pin.IN / OUT constants).
  setupPin(gpio: number, mode: number): void {
    const pin = this.board().pin(`GPIO${gpio}`);
    pin.mode = mode === 0 ? "IN" : "OUT";
  }

  readPin(gpio: number): number {
    const pin = this.board().pin(`GPIO${gpio}`);
    return pin.value === "HIGH" ? 1 : 0;
  }

  writePin(gpio: number, value: number): void {
    const pin = this.board().pin(`GPIO${gpio}`);
    pin.value = value === 0 ? "LOW" : "HIGH";
  }
}